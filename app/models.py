from datetime import datetime
from sqlalchemy import Column, Integer, String, Text, DateTime, ForeignKey
from sqlalchemy.orm import relationship
from app.database import Base


class Paper(Base):
    """Stores primary metadata and processing status for uploaded research papers."""
    __tablename__ = "papers"

    id = Column(Integer, primary_key=True, index=True)
    original_filename = Column(String(255), nullable=False)
    stored_filename = Column(String(255), nullable=False, unique=True)
    file_path = Column(String(512), nullable=False)
    file_size_bytes = Column(Integer, nullable=False)
    status = Column(String(50), default="PENDING", index=True)  # PENDING, PROCESSING, COMPLETED, FAILED
    error_message = Column(Text, nullable=True)
    uploaded_at = Column(DateTime, default=datetime.utcnow)
    completed_at = Column(DateTime, nullable=True)

    # Relationships
    metadata_rel = relationship("PaperMetadata", back_populates="paper", uselist=False, cascade="all, delete-orphan")
    summary = relationship("PaperSummary", back_populates="paper", uselist=False, cascade="all, delete-orphan")
    assets = relationship("GeneratedAsset", back_populates="paper", cascade="all, delete-orphan")
    logs = relationship("AgentLog", back_populates="paper", cascade="all, delete-orphan")


class PaperMetadata(Base):
    """Stores bibliographic and academic metadata extracted from the research paper."""
    __tablename__ = "paper_metadata"

    id = Column(Integer, primary_key=True, index=True)
    paper_id = Column(Integer, ForeignKey("papers.id", ondelete="CASCADE"), nullable=False, unique=True)
    title = Column(String(512), nullable=True)
    authors = Column(String(512), nullable=True)
    publication_year = Column(String(50), nullable=True)
    journal_conference = Column(String(255), nullable=True)
    abstract_text = Column(Text, nullable=True)
    total_pages = Column(Integer, default=0)
    created_at = Column(DateTime, default=datetime.utcnow)

    # Relationship
    paper = relationship("Paper", back_populates="metadata_rel")


class PaperSummary(Base):
    """Stores structured multi-dimensional summary produced by the Summarizer Agent."""
    __tablename__ = "paper_summaries"

    id = Column(Integer, primary_key=True, index=True)
    paper_id = Column(Integer, ForeignKey("papers.id", ondelete="CASCADE"), nullable=False, unique=True)
    tldr = Column(Text, nullable=True)
    problem_statement = Column(Text, nullable=True)
    key_contributions = Column(Text, nullable=True)
    methodology = Column(Text, nullable=True)
    experimental_results = Column(Text, nullable=True)
    limitations_future_work = Column(Text, nullable=True)
    raw_json = Column(Text, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    # Relationship
    paper = relationship("Paper", back_populates="summary")


class GeneratedAsset(Base):
    """Stores outputs generated by downstream agents (PPT, Emails, Code implementation)."""
    __tablename__ = "generated_assets"

    id = Column(Integer, primary_key=True, index=True)
    paper_id = Column(Integer, ForeignKey("papers.id", ondelete="CASCADE"), nullable=False, index=True)
    asset_type = Column(String(50), nullable=False)  # 'presentation', 'email', 'code'
    title = Column(String(255), nullable=False)
    content_text = Column(Text, nullable=True)       # Used for code text or email body
    file_path = Column(String(512), nullable=True)   # Used for downloadable PPT file path
    metadata_json = Column(Text, nullable=True)      # Additional JSON (e.g., email recipient, code lang)
    created_at = Column(DateTime, default=datetime.utcnow)

    # Relationship
    paper = relationship("Paper", back_populates="assets")


class AgentLog(Base):
    """Audit log tracking step-by-step agent executions, errors, and timing."""
    __tablename__ = "agent_logs"

    id = Column(Integer, primary_key=True, index=True)
    paper_id = Column(Integer, ForeignKey("papers.id", ondelete="CASCADE"), nullable=False, index=True)
    agent_name = Column(String(100), nullable=False)
    log_level = Column(String(20), default="INFO")    # INFO, WARNING, ERROR
    message = Column(Text, nullable=False)
    execution_time_ms = Column(Integer, default=0)
    created_at = Column(DateTime, default=datetime.utcnow)

    # Relationship
    paper = relationship("Paper", back_populates="logs")
