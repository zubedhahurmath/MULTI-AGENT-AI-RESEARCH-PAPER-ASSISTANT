import os
import uuid
import logging
from pathlib import Path
from typing import List, Dict, Any, Optional
from app.config import settings

logger = logging.getLogger("ppt_builder")

try:
    from pptx import Presentation
    from pptx.util import Inches, Pt
    from pptx.dml.color import RGBColor
    from pptx.enum.text import PP_ALIGN
    from pptx.enum.shapes import MSO_SHAPE
    PPTX_AVAILABLE = True
except ImportError:
    Presentation = None
    Inches = None
    Pt = None
    RGBColor = None
    PP_ALIGN = None
    MSO_SHAPE = None
    PPTX_AVAILABLE = False


class PPTBuilderService:
    """Service to create professional academic PowerPoint presentation decks using python-pptx."""

    # Academic & Corporate Color Palette
    PRIMARY_COLOR = RGBColor(26, 54, 93)     # Deep Academic Navy
    ACCENT_COLOR = RGBColor(14, 116, 144)    # Modern Cyan / Ocean
    TEXT_MAIN = RGBColor(30, 41, 59)         # Slate Charcoal
    TEXT_MUTED = RGBColor(100, 116, 139)     # Soft Grey
    BG_LIGHT = RGBColor(248, 250, 252)       # Light Off-White
    WHITE = RGBColor(255, 255, 255)

    def __init__(self, output_dir: Optional[Path] = None):
        self.output_dir = output_dir or settings.PRESENTATION_DIR
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def create_presentation(
        self,
        paper_title: str,
        authors: Optional[str],
        slides_data: List[Dict[str, Any]],
        paper_id: Optional[int] = None
    ) -> str:
        """
        Build and save a full .pptx presentation file based on structured slide definitions.
        Returns the absolute file path to the saved presentation.
        """
        if not PPTX_AVAILABLE:
            raise RuntimeError("python-pptx library is not installed in the environment.")

        prs = Presentation()
        # Set 16:9 widescreen dimensions (13.33 x 7.5 inches)
        prs.slide_width = Inches(13.333)
        prs.slide_height = Inches(7.5)
        blank_slide_layout = prs.slide_layouts[6]  # Blank slide for maximum custom layout control

        # --- Slide 1: Title Slide ---
        self._build_title_slide(prs, blank_slide_layout, paper_title, authors)

        # --- Slides 2 to N: Content Slides ---
        for index, slide_info in enumerate(slides_data, start=2):
            title = slide_info.get("title", f"Slide {index}")
            bullets = slide_info.get("bullets", [])
            category = slide_info.get("category", "Analysis")
            notes = slide_info.get("speaker_notes", "")
            self._build_content_slide(prs, blank_slide_layout, title, bullets, category, notes, index, len(slides_data) + 1)

        # Save to presentations directory with safe unique filename
        filename = f"presentation_{paper_id or 'deck'}_{uuid.uuid4().hex[:8]}.pptx"
        file_path = self.output_dir / filename
        prs.save(str(file_path))
        logger.info(f"Generated presentation saved to: {file_path}")
        return str(file_path)

    def _build_title_slide(self, prs, layout, title: str, authors: Optional[str]) -> None:
        """Create an elegant academic title slide."""
        slide = prs.slides.add_slide(layout)

        # Background decorative accent banner
        accent_shape = slide.shapes.add_shape(
            MSO_SHAPE.RECTANGLE,
            Inches(0), Inches(0), Inches(13.333), Inches(0.4)
        )
        accent_shape.fill.solid()
        accent_shape.fill.fore_color.rgb = self.ACCENT_COLOR
        accent_shape.line.color.rgb = self.ACCENT_COLOR

        # Main Title Box
        title_box = slide.shapes.add_textbox(Inches(1.2), Inches(2.0), Inches(10.9), Inches(2.5))
        tf = title_box.text_frame
        tf.word_wrap = True
        p_title = tf.paragraphs[0]
        p_title.text = title or "Research Paper Presentation"
        p_title.font.size = Pt(36)
        p_title.font.bold = True
        p_title.font.color.rgb = self.PRIMARY_COLOR
        p_title.font.name = "Calibri"

        # Subtitle / Authors Box
        sub_box = slide.shapes.add_textbox(Inches(1.2), Inches(4.7), Inches(10.9), Inches(1.5))
        tf_sub = sub_box.text_frame
        tf_sub.word_wrap = True
        p_authors = tf_sub.paragraphs[0]
        p_authors.text = f"Authors: {authors or 'Academic Researchers'}"
        p_authors.font.size = Pt(20)
        p_authors.font.color.rgb = self.TEXT_MUTED
        p_authors.font.name = "Calibri"

        p_affil = tf_sub.add_paragraph()
        p_affil.text = "Generated by Multi-Agent AI Research Paper Assistant"
        p_affil.font.size = Pt(14)
        p_affil.font.italic = True
        p_affil.font.color.rgb = self.ACCENT_COLOR

    def _build_content_slide(
        self,
        prs,
        layout,
        title: str,
        bullets: List[str],
        category: str,
        speaker_notes: str,
        slide_num: int,
        total_slides: int
    ) -> None:
        """Build standard content slide with banner, category badge, and formatted bullet points."""
        slide = prs.slides.add_slide(layout)

        # Top Accent Line
        top_bar = slide.shapes.add_shape(
            MSO_SHAPE.RECTANGLE,
            Inches(0), Inches(0), Inches(13.333), Inches(0.15)
        )
        top_bar.fill.solid()
        top_bar.fill.fore_color.rgb = self.ACCENT_COLOR
        top_bar.line.color.rgb = self.ACCENT_COLOR

        # Category Tag
        cat_box = slide.shapes.add_textbox(Inches(1.0), Inches(0.5), Inches(8.0), Inches(0.4))
        tf_cat = cat_box.text_frame
        p_cat = tf_cat.paragraphs[0]
        p_cat.text = category.upper()
        p_cat.font.size = Pt(11)
        p_cat.font.bold = True
        p_cat.font.color.rgb = self.ACCENT_COLOR
        p_cat.font.name = "Calibri"

        # Slide Title
        title_box = slide.shapes.add_textbox(Inches(1.0), Inches(0.9), Inches(11.3), Inches(1.0))
        tf_title = title_box.text_frame
        tf_title.word_wrap = True
        p_title = tf_title.paragraphs[0]
        p_title.text = title
        p_title.font.size = Pt(28)
        p_title.font.bold = True
        p_title.font.color.rgb = self.PRIMARY_COLOR
        p_title.font.name = "Calibri"

        # Bullet Points Body
        body_box = slide.shapes.add_textbox(Inches(1.0), Inches(2.1), Inches(11.3), Inches(4.5))
        tf_body = body_box.text_frame
        tf_body.word_wrap = True

        for i, bullet in enumerate(bullets):
            p = tf_body.paragraphs[0] if i == 0 else tf_body.add_paragraph()
            p.text = f"•  {bullet}"
            p.font.size = Pt(18)
            p.font.color.rgb = self.TEXT_MAIN
            p.font.name = "Calibri"
            p.space_after = Pt(14)

        # Slide Number Footer
        footer_box = slide.shapes.add_textbox(Inches(10.5), Inches(6.8), Inches(2.0), Inches(0.4))
        p_foot = footer_box.text_frame.paragraphs[0]
        p_foot.text = f"{slide_num} / {total_slides}"
        p_foot.font.size = Pt(11)
        p_foot.font.color.rgb = self.TEXT_MUTED
        p_foot.alignment = PP_ALIGN.RIGHT

        # Speaker Notes
        if speaker_notes:
            notes_slide = slide.notes_slide
            text_frame = notes_slide.notes_text_frame
            text_frame.text = speaker_notes


# Singleton instance
ppt_builder_service = PPTBuilderService()
